function trackOf(sector: SectorBrief): Track {
  return TRACKS[sector.key] ?? genericTrack(sector.label);
}

/** 这个板块按哪几个栏目梳理 */
export function sectorTabs(sector: SectorBrief): string[] {
  return trackOf(sector).tabs.map((t) => t.name);
}

/**
 * 分步提示词：第 1 步读研报、按栏目整理；之后每个栏目一步，产出一页笔记。
 * `year` 默认取今年：提示词里「读哪年的研报」不能写死，明年打开还写今年就读旧了。
 */
export function sectorSteps(sector: SectorBrief, year = new Date().getFullYear()): SectorStep[] {
  const { focus, tabs } = trackOf(sector);
  const total = tabs.length + 1;
  const tabList = tabs.map((t, i) => `${NUMS[i]} ${t.name}`).join("　");
  const nodes = sector.verified && sector.nodes.length
    ? `\n   这个板块已核实的核心环节有：${sector.nodes.join("、")}，整理时都要覆盖到。`
    : "";
  // 开头带上板块名：回答「存进记录」时标题取的是提问开头那几个字，不带名字几个板块的笔记分不清
  const first = `我们来梳理「${sector.label}」这个产业板块（${sector.tagline}），你是我的产业研究助手。
接下来我会分 ${total} 步给你指令，每一步只产出一页内容；不要跳步，也不要自由发挥。

第 1 步，先读研报、按栏目整理：
1. 如果我的资料库里有和${sector.label}相关的研报，先读这些；再去找 ${year} 年和 ${year - 1} 年的公开行业研报、权威资料补充。
   ${focus}${nodes}
2. 把读到的要点按这 ${tabs.length} 个栏目归类整理：${tabList}。
3. 规则：
   · 只做产业研究 —— 讲技术、产业链、格局和跟踪信号；提到公司时只讲它在产业链里的位置和角色。
   · 每个关键数字后面写清来源和年份；查不到就写「未查到」，不要凭记忆补。
   · 我后面提示词里举的数字和判断只是参考，一律以你查到的资料为准，对不上就照实写。
整理完，把要点按 ${tabs.length} 个栏目分别列给我看，再等我下一步。`;
  return [
    { n: 1, title: "读研报，按栏目整理要点", prompt: first },
    ...tabs.map((t, i) => ({
      n: i + 2,
      title: `${t.name}：${t.headline}`,
      prompt: `「${sector.label}」第 ${i + 2} 步，产出【${t.name}】页：
${t.body}

写成一篇完整的 Markdown 笔记，标题用「${sector.label} · ${t.name}」；能用表格的地方用表格；
关键数字后面注明来源和年份，查不到写「未查到」。`,
    })),
  ];
}
